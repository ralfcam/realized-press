#!/usr/bin/env python3
"""Realized Press BWE — Turnkey Google Ads OAuth2 Desktop Flow & Setup Tool (`BWE v0.6.1`, `ARC-74`).

Interactive and CLI setup script to generate a Google Ads OAuth2 refresh token and configure
`google-ads.yaml` in the repository root.

Docs: https://developers.google.com/google-ads/api/docs/first-call/overview
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
if str(ROOT / "scripts") not in sys.path:
    sys.path.insert(0, str(ROOT / "scripts"))

from gads_client import check_environment  # noqa: E402

OAUTH_SCOPES = ["https://www.googleapis.com/auth/adwords"]


def run_oauth_flow(client_id: str, client_secret: str, no_browser: bool = False) -> str:
    """Launch Desktop OAuth2 authorization flow and return refresh token."""
    try:
        from google_auth_oauthlib.flow import InstalledAppFlow
    except ImportError:
        raise SystemExit(
            "[ERROR] `google-auth-oauthlib` is required for turnkey OAuth2 token generation.\n"
            "Install it via:\n"
            "    pip install google-auth-oauthlib"
        )

    client_config = {
        "installed": {
            "client_id": client_id,
            "client_secret": client_secret,
            "auth_uri": "https://accounts.google.com/o/oauth2/auth",
            "token_uri": "https://oauth2.googleapis.com/token",
        }
    }

    flow = InstalledAppFlow.from_client_config(client_config, scopes=OAUTH_SCOPES)
    if no_browser:
        print("\nOpening authorization URL in console mode...")
        creds = flow.run_local_server(open_browser=False, port=0)
    else:
        print("\nOpening your default browser to authorize Realized Press BWE with Google Ads...")
        try:
            creds = flow.run_local_server(port=0)
        except Exception as exc:
            print(f"[WARN] Local browser flow failed ({exc}). Retrying with open_browser=False...")
            creds = flow.run_local_server(open_browser=False, port=0)

    if not creds.refresh_token:
        raise ValueError(
            "No refresh token was returned by Google. Ensure the OAuth consent screen is configured "
            "as 'Desktop app' or 'External' with offline access."
        )
    return str(creds.refresh_token)


def write_google_ads_yaml(
    output_path: Path,
    developer_token: str,
    client_id: str,
    client_secret: str,
    refresh_token: str,
    customer_id: str,
    login_customer_id: str = "",
) -> None:
    """Write sanitized credentials into google-ads.yaml."""
    cid_clean = re.sub(r"\D", "", customer_id)
    login_cid_clean = re.sub(r"\D", "", login_customer_id) if login_customer_id else ""

    lines = [
        "# Google Ads API client configuration (Realized Press BWE v0.6.1)",
        "# Generated by scripts/gads_auth_setup.py",
        f'developer_token: "{developer_token.strip()}"',
        f'client_id: "{client_id.strip()}"',
        f'client_secret: "{client_secret.strip()}"',
        f'refresh_token: "{refresh_token.strip()}"',
        "",
    ]
    if login_cid_clean:
        lines.append(f'login_customer_id: "{login_cid_clean}"')
    else:
        lines.append('# login_customer_id: "INSERT_MCC_CUSTOMER_ID_IF_APPLICABLE"')

    lines += [
        f'customer_id: "{cid_clean}"',
        "",
        "use_proto_plus: true",
        "",
    ]

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[OK] Wrote credentials configuration to: {output_path}")


def prompt_value(prompt: str, default: str = "", is_secret: bool = False) -> str:
    """Prompt user for input if default is empty."""
    if default:
        return default
    if not sys.stdin.isatty():
        return ""
    suffix = " (press Enter to skip): " if not is_secret else ": "
    val = input(prompt + suffix).strip()
    return val


def main() -> int:
    parser = argparse.ArgumentParser(description="Turnkey Google Ads API OAuth2 Setup & Configurator (BWE v0.6.1)")
    parser.add_argument("--client-id", help="Google Cloud OAuth 2.0 Client ID")
    parser.add_argument("--client-secret", help="Google Cloud OAuth 2.0 Client Secret")
    parser.add_argument("--developer-token", help="Google Ads Developer Token (Basic or Standard Access)")
    parser.add_argument("--customer-id", help="Operating Google Ads Customer ID (10 digits without dashes)")
    parser.add_argument("--login-customer-id", help="Manager Account ID (MCC, 10 digits without dashes)")
    parser.add_argument("--refresh-token", help="Skip OAuth2 browser flow if you already have a refresh token")
    parser.add_argument("--output", type=Path, default=ROOT / "google-ads.yaml", help="Destination config file path")
    parser.add_argument("--no-browser", action="store_true", help="Do not attempt to open a desktop web browser")
    parser.add_argument("--non-interactive", action="store_true", help="Fail instead of prompting if fields are missing")
    parser.add_argument("--check", action="store_true", help="Only verify existing configuration")
    args = parser.parse_args()

    if args.check:
        print("=== Checking Existing Google Ads Environment ===")
        report = check_environment(config_path=args.output)
        print(f"SDK Installed:         {'PASS' if report['sdk_installed'] else 'FAIL'}")
        print(f"Config File:           {report['config_file'] or 'None'}")
        print(f"Customer ID:           {report['customer_id'] or 'None'}")
        print(f"Login Customer ID:     {report['login_customer_id'] or 'None'}")
        print(f"Client Ready:          {'PASS' if report['is_available'] else 'DISABLED'}")
        return 0 if report["is_available"] else 1

    dev_token = args.developer_token or os.getenv("GOOGLE_ADS_DEVELOPER_TOKEN", "")
    client_id = args.client_id or os.getenv("GOOGLE_ADS_CLIENT_ID", "")
    client_secret = args.client_secret or os.getenv("GOOGLE_ADS_CLIENT_SECRET", "")
    customer_id = args.customer_id or os.getenv("GOOGLE_ADS_CUSTOMER_ID", "")
    login_cid = args.login_customer_id or os.getenv("GOOGLE_ADS_LOGIN_CUSTOMER_ID", "")
    refresh_token = args.refresh_token or os.getenv("GOOGLE_ADS_REFRESH_TOKEN", "")

    if not args.non_interactive and sys.stdin.isatty():
        print("=== Realized Press BWE: Google Ads API Turnkey Setup ===")
        print("This tool will configure your local `google-ads.yaml`.\n")
        if not dev_token:
            dev_token = prompt_value("Enter your Google Ads Developer Token: ")
        if not client_id:
            client_id = prompt_value("Enter your OAuth2 Client ID: ")
        if not client_secret:
            client_secret = prompt_value("Enter your OAuth2 Client Secret: ")
        if not customer_id:
            customer_id = prompt_value("Enter your 10-digit Customer ID: ")
        if not login_cid:
            login_cid = prompt_value("Enter your 10-digit Manager Customer ID (MCC) [Optional]: ")

    missing = []
    if not dev_token:
        missing.append("developer_token (--developer-token or GOOGLE_ADS_DEVELOPER_TOKEN)")
    if not client_id:
        missing.append("client_id (--client-id or GOOGLE_ADS_CLIENT_ID)")
    if not client_secret:
        missing.append("client_secret (--client-secret or GOOGLE_ADS_CLIENT_SECRET)")
    if not customer_id:
        missing.append("customer_id (--customer-id or GOOGLE_ADS_CUSTOMER_ID)")

    if missing:
        print("[ERROR] Missing required configuration values:")
        for m in missing:
            print(f"  - {m}")
        print("\nPass these via command-line arguments or run interactively in a terminal.")
        return 1

    if not refresh_token:
        print(f"\nStarting OAuth2 consent flow for client: {client_id[:12]}...")
        refresh_token = run_oauth_flow(client_id, client_secret, no_browser=args.no_browser)
        print("[OK] Successfully generated OAuth2 refresh token!")

    write_google_ads_yaml(
        output_path=args.output,
        developer_token=dev_token,
        client_id=client_id,
        client_secret=client_secret,
        refresh_token=refresh_token,
        customer_id=customer_id,
        login_customer_id=login_cid,
    )

    print("\n=== Verifying Configured Client ===")
    report = check_environment(config_path=args.output)
    if report["is_available"]:
        print("[SUCCESS] Google Ads API is fully configured and ready for live demand enrichment!")
        return 0
    else:
        print("[WARN] Configuration written, but client is not yet operational:")
        if not report["sdk_installed"]:
            print("  - google-ads SDK is not installed: run `pip install google-ads>=25.1.0`")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
