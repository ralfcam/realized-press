# Visual Graph Explorer SVG Generator
# ---------------------------------------------------------------------------

def generate_series_map_svg(conn: sqlite3.Connection, series_slug: str) -> str:
    """Generate an interactive SVG Three-Lens Evidence Graph."""
    # Fetch chapters
    ch_rows = conn.execute(
        """SELECT node_id, label, metadata_json FROM okf_nodes
           WHERE series_slug = ? AND node_type = 'chapter'
           ORDER BY node_id ASC LIMIT 18""",
        (series_slug,),
    ).fetchall()

    # Fetch cards
    card_rows = conn.execute(
        """SELECT node_id, label, metadata_json FROM okf_nodes
           WHERE series_slug = ? AND node_type = 'card'
           ORDER BY node_id ASC LIMIT 25""",
        (series_slug,),
    ).fetchall()

    if not ch_rows or not card_rows:
        return "<svg width='600' height='200' xmlns='http://www.w3.org/2000/svg'><text x='20' y='50' fill='#a8a29e'>No graph nodes indexed yet. Run build_series_knowledge_graph.</text></svg>"

    width = 960
    height = max(500, max(len(ch_rows), len(card_rows)) * 32 + 80)

    # 3 Columns:
    # Left (x=160): Chapters
    # Center (x=480): OKF Evidence Cards
    # Right (x=800): Three Lenses
    lenses = (
        [("Technical", "#38bdf8"), ("Organizational", "#fbbf24"), ("Philosophical", "#c084fc")]
        if "architectures" in series_slug
        else [("Science", "#34d399"), ("Interpretation", "#fbbf24"), ("Art", "#f43f5e")]
    )

    svg_parts: list[str] = [
        f"<svg width='100%' height='{height}' viewBox='0 0 {width} {height}' xmlns='http://www.w3.org/2000/svg' class='bg-stone-950 font-mono text-xs rounded-xl border border-stone-800 p-4'>",
        "<defs>",
        "  <linearGradient id='grad-edge' x1='0%' y1='0%' x2='100%' y2='0%'>",
        "    <stop offset='0%' stop-color='#f59e0b' stop-opacity='0.4'/>",
        "    <stop offset='100%' stop-color='#10b981' stop-opacity='0.4'/>",
        "  </linearGradient>",
        "</defs>",
        f"<text x='40' y='30' fill='#e7e5e4' font-size='14' font-weight='bold'>OKF v0.3 Evidence &amp; Lens Graph: {series_slug}</text>",
        f"<text x='40' y='50' fill='#78716c' font-size='11'>Chapters ({len(ch_rows)}) ── Cites ──> Cards ({len(card_rows)}) ── Categorized By ──> Lenses (3)</text>",
    ]

    ch_y: dict[str, int] = {}
    for i, ch in enumerate(ch_rows):
        y = 90 + i * 28
        ch_y[ch["node_id"]] = y
        clean_lbl = ch["label"][:24]
        svg_parts.append(
            f"<g class='cursor-pointer'><circle cx='120' cy='{y}' r='5' fill='#d97706'/>"
            f"<text x='110' y='{y + 4}' fill='#d6d3d1' font-size='10' text-anchor='end'>{clean_lbl}</text></g>"
        )

    card_y: dict[str, int] = {}
    for j, cd in enumerate(card_rows):
        y = 90 + j * 24
        card_y[cd["node_id"]] = y
        cm = json.loads(cd["metadata_json"])
        grade = cm.get("certainty_grade", "Moderate")
        color = "#10b981" if grade == "High" else ("#f59e0b" if grade == "Moderate" else "#f43f5e")
        clean_lbl = cd["label"][:28]
        svg_parts.append(
            f"<g class='cursor-pointer'><circle cx='480' cy='{y}' r='5' fill='{color}'/>"
            f"<text x='495' y='{y + 4}' fill='#e7e5e4' font-size='10'>{clean_lbl} [{grade}]</text></g>"
        )

    lens_y: dict[str, int] = {}
    for k, (lname, lcolor) in enumerate(lenses):
        y = 140 + k * 80
        lens_y[lname.lower()] = y
        svg_parts.append(
            f"<g><rect x='800' y='{y - 14}' width='130' height='28' rx='6' fill='{lcolor}' fill-opacity='0.15' stroke='{lcolor}' stroke-width='1.5'/>"
            f"<text x='865' y='{y + 4}' fill='{lcolor}' font-size='11' font-weight='bold' text-anchor='middle'>{lname} Lens</text></g>"
        )

    # Render edges from chapters to cards
    edges = conn.execute(
        """SELECT source_id, target_id FROM okf_edges
           WHERE series_slug = ? AND edge_type = 'CITED_IN_MOVEMENT' LIMIT 60""",
        (series_slug,),
    ).fetchall()

    for e in edges:
        card_id = e["source_id"]
        # Find chapter from movement target_id
        mv_id = e["target_id"]
        ch_parts = mv_id.split(":")
        if len(ch_parts) >= 4:
            ch_sub_id = f"ch:{ch_parts[1]}:{ch_parts[2]}:{ch_parts[3]}"
            y1 = ch_y.get(ch_sub_id)
            y2 = card_y.get(card_id)
            if y1 and y2:
                svg_parts.append(
                    f"<path d='M 125 {y1} C 300 {y1}, 300 {y2}, 475 {y2}' stroke='url(#grad-edge)' stroke-width='1' fill='none'/>"
                )

    svg_parts.append("</svg>")
    return "\n".join(svg_parts)
