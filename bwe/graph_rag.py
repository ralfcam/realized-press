def parse_chapter_file(ch_path: Path, series_slug: str, book_slug: str) -> dict[str, Any]:
    text = ch_path.read_text(encoding="utf-8", errors="replace")
    ch_slug = ch_path.stem

    # Chapter number from filename (e.g. 05-becoming-a-mind.md -> 5)
    num_match = re.match(r"^(\d+)", ch_slug)
    ch_num = int(num_match.group(1)) if num_match else 1

    # Extract title and subtitle
    lines = text.splitlines()
    title = ch_slug
    subtitle = ""
    for idx, line in enumerate(lines[:6]):
        if line.startswith("# "):
            title = line.lstrip("# ").strip()
            # If next non-empty line starts with *, it's subtitle
            for next_line in lines[idx + 1:idx + 4]:
                nl = next_line.strip()
                if nl.startswith("*") and nl.endswith("*"):
                    subtitle = nl.strip("* ").strip()
                    break
            break

    # Split into body and ## Notes
    notes_start = -1
    for idx, line in enumerate(lines):
        if line.strip().lower() == "## notes":
            notes_start = idx
            break

    body_lines = lines[:notes_start] if notes_start != -1 else lines
    notes_lines = lines[notes_start:] if notes_start != -1 else []
    body_text = "\n".join(body_lines)
    notes_text = "\n".join(notes_lines)

    # Extract prologue anchor (first 1-2 paragraphs before first ## heading)
    prologue_paras: list[str] = []
    in_prologue = True
    for line in body_lines:
        if line.startswith("## "):
            in_prologue = False
            break
        if in_prologue and line.strip() and not line.startswith("#") and not line.startswith("*") and not line.startswith(">"):
            prologue_paras.append(line.strip())
            if len(prologue_paras) >= 2:
                break
    prologue_anchor = " ".join(prologue_paras)

    # Extract closing anchor and takeaway
    closing_paras: list[str] = []
    takeaway_core_rule = ""
    for line in reversed(body_lines):
        if "The Core Rule:" in line or "Core Rule:" in line:
            takeaway_core_rule = line.split(":", 1)[1].strip()
        elif not takeaway_core_rule and "What You Can Let Go Of:" in line:
            takeaway_core_rule = line.strip()
        if not closing_paras and line.strip() and not line.startswith("<") and not line.startswith("</") and not line.startswith("###") and not line.startswith("-") and not line.startswith("##"):
            closing_paras.append(line.strip())
            if len(closing_paras) >= 1:
                break
    closing_anchor = " ".join(reversed(closing_paras))

    # Parse movements
    movements: list[dict[str, Any]] = []
    heading_indices: list[tuple[int, str, str]] = []  # (line_idx, heading_num, heading_text)

    for idx, line in enumerate(body_lines):
        m = re.match(r"^##\s+([IVXLCDM]+|\d+)\.\s+(.+)$", line)
        if m:
            heading_indices.append((idx, m.group(1), m.group(2).strip()))
        elif line.startswith("## ") and not line.strip().lower().startswith("## notes") and not line.strip().lower().startswith("## linked"):
            # Non-numeral section heading (e.g. ## Technical lens — ...)
            clean_h = line.lstrip("# ").strip()
            num_label = f"S{len(heading_indices) + 1}"
            heading_indices.append((idx, num_label, clean_h))

    for m_idx, (start_line, h_num, h_text) in enumerate(heading_indices):
        end_line = heading_indices[m_idx + 1][0] if m_idx + 1 < len(heading_indices) else len(body_lines)
        mv_lines = body_lines[start_line:end_line]
        mv_text = "\n".join(mv_lines)

        # Detect dominant lens
        h_low = h_text.lower()
        if any(w in h_low for w in ("technical", "machine", "algorithm", "network", "gradient", "math")):
            lens = "technical"
        elif any(w in h_low for w in ("organizational", "enterprise", "business", "institution", "audit")):
            lens = "organizational"
        elif any(w in h_low for w in ("philosophical", "nietzsche", "borges", "bergson", "mind", "ethics")):
            lens = "philosophical"
        elif any(w in h_low for w in ("science", "lab", "trial", "biology")):
            lens = "science"
        elif any(w in h_low for w in ("interpretation", "meaning")):
            lens = "interpretation"
        elif any(w in h_low for w in ("art", "parenting", "caring")):
            lens = "art"
        else:
            lens = "technical"

        # Check for set-piece
        has_set_piece = any(w in mv_text.lower() for w in ("drawbridge", "mobile-conjugate", "4-beat", "then vs now", "landmark"))

        movements.append({
            "movement_num": h_num,
            "heading": h_text,
            "dominant_lens": lens,
            "word_count": len(mv_text.split()),
            "has_set_piece": has_set_piece,
            "text": mv_text,
        })

    # If no ## movements were found, treat entire body as Movement I
    if not movements:
        movements.append({
            "movement_num": "I",
            "heading": title,
            "dominant_lens": "technical" if "architectures" in series_slug else "science",
            "word_count": len(body_text.split()),
            "has_set_piece": False,
            "text": body_text,
        })

    # Parse notes definitions
    notes_defs: dict[str, str] = {}
    for m in DEF_FN_RE.finditer(notes_text):
        notes_defs[m.group(1)] = m.group(2).strip()

    # Parse linked cards section
    linked_cards: list[str] = []
    for line in notes_lines:
        m = LINKED_CARD_RE.search(line)
        if m:
            slug = m.group(1).strip()
            if slug not in linked_cards and slug != "index":
                linked_cards.append(slug)

    return {
        "chapter_slug": ch_slug,
        "chapter_num": ch_num,
        "title": title,
        "subtitle": subtitle,
        "prologue_anchor": prologue_anchor,
        "closing_anchor": closing_anchor,
        "takeaway_core_rule": takeaway_core_rule,
        "movements": movements,
        "notes_defs": notes_defs,
        "linked_cards": linked_cards,
        "body_text": body_text,
        "word_count": len(body_text.split()),
    }


def extract_footnote_sentences(movement_text: str) -> list[dict[str, Any]]:
    """Extract each [^fn_id] occurrence, its surrounding sentence, and the observed epistemic verb."""
    results: list[dict[str, Any]] = []
    # Split text into sentences cleanly
    cleaned = re.sub(r"\n+", " ", movement_text)
    # Match sentences roughly by punctuation
    raw_sentences = re.split(r"(?<=[.!?])\s+", cleaned)

    for sent in raw_sentences:
        fn_matches = INLINE_FN_RE.findall(sent)
        if not fn_matches:
            continue

        # Extract epistemic verbs in this sentence
        words = [w.lower().strip(".,;:\"'!?()") for w in sent.split()]
        observed_verb = "stated"
        for v in HIGH_CERTAINTY_VERBS:
            if v in words:
                observed_verb = v
                break
        if observed_verb == "stated":
            for v in MODERATE_CERTAINTY_VERBS:
                if v in words:
                    observed_verb = v
                    break
        if observed_verb == "stated":
            for v in LOW_CERTAINTY_VERBS:
                if v in sent.lower():
                    observed_verb = v
                    break

        for fn_id in fn_matches:
            results.append({
                "footnote_id": fn_id,
                "sentence_text": sent.strip(),
                "observed_verb": observed_verb,
            })

    return results


