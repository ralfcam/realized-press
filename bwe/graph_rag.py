def parse_card_file(card_path: Path, series_slug: str, book_slug: str) -> dict[str, Any]:
    text = card_path.read_text(encoding="utf-8", errors="replace")
    fm: dict[str, Any] = {}
    body = text

    if text.startswith("---"):
        parts = text.split("---", 2)
        if len(parts) >= 3:
            try:
                fm = yaml.safe_load(parts[1]) or {}
            except Exception:
                fm = {}
            body = parts[2]

    card_slug = card_path.stem
    title = fm.get("title") or _extract_h1(body) or card_slug

    # OKF v0.3 explicit fields or v0.2 fallback
    okf_version = str(fm.get("okf_version", "0.2"))
    card_id = fm.get("card_id") or card_slug

    # Certainty grade
    raw_conf = str(fm.get("confidence") or fm.get("certainty_grade") or "").strip().lower()
    if "high" in raw_conf:
        grade = "High"
    elif "mod" in raw_conf:
        grade = "Moderate"
    elif "low" in raw_conf:
        grade = "Low"
    else:
        # Check body
        grade_match = re.search(r"\*\*Grade\*\*:\s*([A-Za-z -]+)", body, re.IGNORECASE)
        if grade_match:
            g_low = grade_match.group(1).lower()
            if "high" in g_low:
                grade = "High"
            elif "mod" in g_low:
                grade = "Moderate"
            elif "low" in g_low:
                grade = "Low"
            else:
                grade = "Moderate"
        else:
            grade = "Moderate"

    # Primary lens
    primary_lens = fm.get("primary_lens")
    if not primary_lens:
        domains = fm.get("series_domains") or fm.get("atlas_domains") or []
        if domains and isinstance(domains, list):
            primary_lens = str(domains[0]).lower()
        else:
            # Infer from path or series
            if "architectures-of-memory" in series_slug:
                primary_lens = "technical"
            else:
                primary_lens = "science"

    # Attenuation class
    attenuation_class = fm.get("attenuation_class")
    if not attenuation_class:
        if "largely confounded" in body.lower() or "over 50" in body.lower():
            attenuation_class = "largely_confounded_over_50pct"
        elif "partially confounded" in body.lower() or "20–50" in body.lower() or "20-50" in body.lower():
            attenuation_class = "partially_confounded_20_50pct"
        elif "robust" in body.lower() or "under 20" in body.lower():
            attenuation_class = "robust_under_20pct"
        else:
            attenuation_class = "not_applicable"

    # Allowed & forbidden verbs
    allowed_verbs = fm.get("allowed_verbs")
    forbidden_verbs = fm.get("forbidden_verbs")
    if not allowed_verbs:
        if grade == "High":
            allowed_verbs = ["shows", "demonstrates", "establishes", "prevents", "preserves"]
            forbidden_verbs = ["proves_universally", "solves_all_sequence_learning"]
        elif grade == "Moderate":
            allowed_verbs = ["suggests", "indicates", "points toward"]
            forbidden_verbs = ["proves", "causes", "establishes", "demonstrates"]
        else:
            allowed_verbs = ["is associated with", "correlates with", "tracks with"]
            forbidden_verbs = ["causes", "prevents", "proves", "establishes", "demonstrates"]

    # Canonical metaphors
    canonical_metaphors = fm.get("canonical_metaphors") or {}
    if not isinstance(canonical_metaphors, dict):
        canonical_metaphors = {}
    if not canonical_metaphors.get("body_prose"):
        canonical_metaphors["body_prose"] = title
    if not canonical_metaphors.get("spoken_tts"):
        canonical_metaphors["spoken_tts"] = canonical_metaphors["body_prose"]

    # Jargon mappings
    jargon_mappings = fm.get("jargon_mappings") or []
    if not isinstance(jargon_mappings, list):
        jargon_mappings = []

    # Escalation plan
    escalation_plan = fm.get("escalation_plan") or {}
    if not isinstance(escalation_plan, dict):
        escalation_plan = {}

    # Contradicts or bounds
    contradicts_or_bounds = fm.get("contradicts_or_bounds") or []
    if not isinstance(contradicts_or_bounds, list):
        contradicts_or_bounds = [str(contradicts_or_bounds)]

    # Locked bib keys
    locked_bib_keys = fm.get("locked_bib_keys") or []
    if not locked_bib_keys:
        for s in fm.get("sources") or []:
            if isinstance(s, dict) and s.get("id"):
                locked_bib_keys.append(str(s["id"]))

    return {
        "card_slug": card_slug,
        "card_id": card_id,
        "okf_version": okf_version,
        "title": title,
        "primary_lens": str(primary_lens).lower(),
        "certainty_grade": grade,
        "attenuation_class": str(attenuation_class),
        "allowed_verbs": list(allowed_verbs),
        "forbidden_verbs": list(forbidden_verbs or []),
        "canonical_metaphors": canonical_metaphors,
        "jargon_mappings": jargon_mappings,
        "escalation_plan": escalation_plan,
        "contradicts_or_bounds": [str(c) for c in contradicts_or_bounds],
        "locked_bib_keys": [str(k) for k in locked_bib_keys],
        "body_preview": body[:400].strip(),
    }


def _extract_h1(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line.lstrip("# ").strip()
    return ""


