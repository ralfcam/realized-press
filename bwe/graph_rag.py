def build_series_knowledge_graph(
    conn: sqlite3.Connection,
    repo_root: Path,
    series_slug: Optional[str] = None,
) -> None:
    """Compile Git-native Markdown/YAML/BibTeX into okf_nodes and okf_edges."""
    series_dir = repo_root / "series"
    if not series_dir.is_dir():
        return

    # Discover all distinct series slugs from chapter paths
    discovered_slugs: set[str] = set()
    for ch in series_dir.glob("**/chapters/*.md"):
        if ch.name.startswith("_") or "preliminary" in ch.parts:
            continue
        rel = ch.relative_to(series_dir).parts
        s_slug, _ = resolve_series_and_book_slug(rel)
        discovered_slugs.add(s_slug)

    series_slugs_to_build: list[str]
    if series_slug:
        series_slugs_to_build = [series_slug]
    else:
        series_slugs_to_build = sorted(discovered_slugs)

    for s_slug in series_slugs_to_build:
        # Clear existing nodes & edges for this series
        conn.execute("DELETE FROM okf_edges WHERE series_slug = ?", (s_slug,))
        conn.execute("DELETE FROM okf_nodes WHERE series_slug = ?", (s_slug,))

        # Locate base directory for this series
        if "/i18n/" in s_slug:
            parent_name, lang = s_slug.split("/i18n/")
            s_base_path = series_dir / parent_name / "i18n" / lang
            parent_base_path = series_dir / parent_name
        else:
            s_base_path = series_dir / s_slug
            parent_base_path = s_base_path

        # 1. Parse Characters
        chars = parse_characters(parent_base_path)
        for c in chars:
            c_node_id = f"char:{s_slug}:{c['person_slug']}"
            conn.execute(
                """INSERT OR REPLACE INTO okf_nodes
                   (node_id, series_slug, book_slug, node_type, label, metadata_json)
                   VALUES (?, ?, ?, ?, ?, ?)""",
                (c_node_id, s_slug, "root", "character", c["full_name"], json.dumps(c)),
            )

        # 2. Parse Jargon Concepts
        jargon_items = parse_jargon(repo_root, s_base_path)
        for j in jargon_items:
            concept_node_id = f"concept:{s_slug}:{j['concept_slug']}"
            conn.execute(
                """INSERT OR REPLACE INTO okf_nodes
                   (node_id, series_slug, book_slug, node_type, label, metadata_json)
                   VALUES (?, ?, ?, ?, ?, ?)""",
                (concept_node_id, s_slug, "root", "concept", j["raw_jargon"], json.dumps(j)),
            )

        # 3. Parse BibTeX Sources across all sources.bib files for this series
        bib_sources: dict[str, dict[str, Any]] = {}
        candidate_bibs = list(s_base_path.glob("**/sources.bib"))
        if not candidate_bibs and parent_base_path != s_base_path:
            candidate_bibs = list(parent_base_path.glob("**/sources.bib"))

        for bib_file in candidate_bibs:
            parsed_bib = parse_sources_bib(bib_file)
            for k, val in parsed_bib.items():
                bib_sources[k] = val
                src_node_id = f"bib:{s_slug}:{k}"
                conn.execute(
                    """INSERT OR REPLACE INTO okf_nodes
                       (node_id, series_slug, book_slug, node_type, label, metadata_json)
                       VALUES (?, ?, ?, ?, ?, ?)""",
                    (src_node_id, s_slug, "root", "source", val["title"], json.dumps(val)),
                )

        # 4. Parse Evidence Cards
        cards: dict[str, dict[str, Any]] = {}
        card_files = list(s_base_path.glob("**/evidence-cards/*.md"))
        if not card_files and parent_base_path != s_base_path:
            card_files = list(parent_base_path.glob("**/evidence-cards/*.md"))

        for card_path in sorted(card_files):
            if card_path.name.startswith("_") or card_path.name.lower() in {"index.md", "readme.md"}:
                continue
            if "preliminary" in card_path.parts:
                continue

            rel_parts = card_path.relative_to(series_dir).parts
            _, book_slug = resolve_series_and_book_slug(rel_parts)
            card_info = parse_card_file(card_path, s_slug, book_slug)
            cards[card_info["card_slug"]] = card_info

            card_node_id = f"card:{s_slug}:{card_info['card_slug']}"
            conn.execute(
                """INSERT OR REPLACE INTO okf_nodes
                   (node_id, series_slug, book_slug, node_type, label, metadata_json)
                   VALUES (?, ?, ?, ?, ?, ?)""",
                (card_node_id, s_slug, book_slug, "card", card_info["title"], json.dumps(card_info)),
            )

            # Edge 1: BACKED_BY_SOURCE (card -> source)
            for bib_key in card_info.get("locked_bib_keys", []):
                src_node_id = f"bib:{s_slug}:{bib_key}"
                conn.execute(
                    """INSERT INTO okf_edges
                       (series_slug, source_id, target_id, edge_type, weight, metadata_json)
                       VALUES (?, ?, ?, 'BACKED_BY_SOURCE', 1.0, '{}')""",
                    (s_slug, card_node_id, src_node_id),
                )

            # Edge 3: CONTRADICTS_OR_BOUNDS (card_A -> card_B)
            for bounded_slug in card_info.get("contradicts_or_bounds", []):
                target_card_id = f"card:{s_slug}:{bounded_slug}"
                conn.execute(
                    """INSERT INTO okf_edges
                       (series_slug, source_id, target_id, edge_type, weight, metadata_json)
                       VALUES (?, ?, ?, 'CONTRADICTS_OR_BOUNDS', 1.0, ?)""",
                    (s_slug, card_node_id, target_card_id, json.dumps({"nature": "bounds"})),
                )

        # 5. Parse Chapters & Movements
        # Collect and filter only chapters belonging to s_slug
        matching_chapter_files: list[tuple[str, Path]] = []
        for ch_path in s_base_path.glob("**/chapters/*.md"):
            if ch_path.name.startswith("_") or ch_path.name.lower() in {"index.md", "readme.md"}:
                continue
            if "preliminary" in ch_path.parts:
                continue
            rel_parts = ch_path.relative_to(series_dir).parts
            act_s_slug, b_slug = resolve_series_and_book_slug(rel_parts)
            if act_s_slug == s_slug:
                matching_chapter_files.append((b_slug, ch_path))

        # Sort chapters by (book_slug, filename)
        matching_chapter_files.sort(key=lambda t: (t[0], t[1].name))

        # Group by book for sequential handoffs
        chapters_by_book: dict[str, list[dict[str, Any]]] = {}
        card_appearance_tracker: dict[str, int] = {}
        last_movement_for_card: dict[str, str] = {}
        character_appearance_tracker: dict[str, int] = {}

        for b_slug, ch_path in matching_chapter_files:
            ch_info = parse_chapter_file(ch_path, s_slug, b_slug)
            ch_node_id = f"ch:{s_slug}:{b_slug}:{ch_info['chapter_slug']}"
            ch_info["node_id"] = ch_node_id
            ch_info["book_slug"] = b_slug

            conn.execute(
                """INSERT OR REPLACE INTO okf_nodes
                   (node_id, series_slug, book_slug, node_type, label, metadata_json)
                   VALUES (?, ?, ?, ?, ?, ?)""",
                (ch_node_id, s_slug, b_slug, "chapter", ch_info["title"], json.dumps(ch_info)),
            )

            chapters_by_book.setdefault(b_slug, []).append(ch_info)

            # Movements inside this chapter
            for mv in ch_info["movements"]:
                mv_node_id = f"mv:{ch_node_id}:{mv['movement_num']}"
                conn.execute(
                    """INSERT OR REPLACE INTO okf_nodes
                       (node_id, series_slug, book_slug, node_type, label, metadata_json)
                       VALUES (?, ?, ?, ?, ?, ?)""",
                    (mv_node_id, s_slug, b_slug, "movement", mv["heading"], json.dumps(mv)),
                )

                # Footnotes & Card citations in this movement
                fn_sentences = extract_footnote_sentences(mv["text"])
                for fs in fn_sentences:
                    fn_id = fs["footnote_id"]
                    note_def = ch_info["notes_defs"].get(fn_id, "")

                    # Resolve footnote to card slug(s)
                    target_card_slugs: list[str] = []
                    card_m = CARD_IN_NOTE_RE.search(note_def)
                    if card_m:
                        clause = note_def[card_m.start():]
                        for m_card in re.finditer(r"(?:evidence-cards/)?([a-z0-9-]+)(?:\.md)", clause, re.IGNORECASE):
                            s = m_card.group(1).strip()
                            if s in cards and s not in target_card_slugs:
                                target_card_slugs.append(s)
                        if not target_card_slugs and card_m.group(1).strip() in cards:
                            target_card_slugs.append(card_m.group(1).strip())

                    fn_clean = re.sub(r"[^a-z0-9]", "", fn_id.lower())
                    if fn_clean.startswith("ch") and len(fn_clean) > 4 and fn_clean[2:4].isdigit():
                        fn_clean_sub = fn_clean[4:]
                    else:
                        fn_clean_sub = fn_clean

                    note_clean = re.sub(r"[^a-z0-9]", "", note_def.lower())

                    # Match by card slug or clean substring
                    if not target_card_slugs:
                        for c_slug in cards:
                            c_clean = re.sub(r"[^a-z0-9]", "", c_slug.lower())
                            if fn_clean_sub and (fn_clean_sub in c_clean or c_clean in fn_clean) and len(fn_clean_sub) >= 4:
                                target_card_slugs.append(c_slug)
                                break

                    # Match by locked bib keys in note text or fn_id
                    if not target_card_slugs:
                        for c_slug, c_data in cards.items():
                            for b_key in c_data.get("locked_bib_keys", []):
                                b_clean = re.sub(r"[^a-z0-9]", "", b_key.lower())
                                if ((b_clean in fn_clean or fn_clean in b_clean or b_clean in note_clean) and len(b_clean) >= 3) or (b_key.lower() in note_def.lower()):
                                    target_card_slugs.append(c_slug)
                                    break
                            if target_card_slugs:
                                break

                    # Match by author and year tokens from card slug in note_def / fn_id
                    if not target_card_slugs:
                        for c_slug, c_data in cards.items():
                            slug_parts = c_slug.split("-")
                            if len(slug_parts) >= 2 and slug_parts[1].isdigit():
                                author_part = slug_parts[0]
                                year_part = slug_parts[1]
                                if author_part in note_def.lower() and (year_part in note_def.lower() or year_part in fn_id.lower()):
                                    target_card_slugs.append(c_slug)
                                    break
                                if author_part in fn_id.lower() and (year_part in fn_id.lower() or year_part in note_def.lower()):
                                    target_card_slugs.append(c_slug)
                                    break

                    # Match by sources in frontmatter
                    if not target_card_slugs:
                        for c_slug, c_data in cards.items():
                            for src in c_data.get("sources", []):
                                s_id = src.get("id", "")
                                s_clean = re.sub(r"[^a-z0-9]", "", s_id.lower())
                                if s_clean and ((s_clean in fn_clean or fn_clean in s_clean or s_clean in note_clean) and len(s_clean) >= 3):
                                    target_card_slugs.append(c_slug)
                                    break
                            if target_card_slugs:
                                break

                    # If still unresolved, check linked_cards
                    if not target_card_slugs and ch_info["linked_cards"]:
                        for lc in ch_info["linked_cards"]:
                            if lc in cards and (fn_id in lc or lc in fn_id):
                                target_card_slugs.append(lc)
                                break

                    for target_card_slug in target_card_slugs:
                        if target_card_slug in cards:
                            cur_ordinal = card_appearance_tracker.get(target_card_slug, 0) + 1
                            card_appearance_tracker[target_card_slug] = cur_ordinal

                            card_target_node_id = f"card:{s_slug}:{target_card_slug}"
                            citation_meta = {
                                "footnote_id": fn_id,
                                "sentence_text": fs["sentence_text"],
                                "observed_epistemic_verb": fs["observed_verb"],
                                "appearance_ordinal": cur_ordinal,
                                "chapter_num": ch_info["chapter_num"],
                                "chapter_slug": ch_info["chapter_slug"],
                                "movement_num": mv["movement_num"],
                            }

                            # Edge 2: CITED_IN_MOVEMENT (card -> movement)
                            conn.execute(
                                """INSERT INTO okf_edges
                                   (series_slug, source_id, target_id, edge_type, weight, metadata_json)
                                   VALUES (?, ?, ?, 'CITED_IN_MOVEMENT', 1.0, ?)""",
                                (s_slug, card_target_node_id, mv_node_id, json.dumps(citation_meta)),
                            )

                            # Edge 7: ESCALATES_TO (mv_prev -> mv_curr) for ordinal >= 2
                            if cur_ordinal >= 2 and target_card_slug in last_movement_for_card:
                                prev_mv_id = last_movement_for_card[target_card_slug]
                                escalates_meta = {
                                    "card_slug": target_card_slug,
                                    "from_ordinal": cur_ordinal - 1,
                                    "to_ordinal": cur_ordinal,
                                }
                                conn.execute(
                                    """INSERT INTO okf_edges
                                       (series_slug, source_id, target_id, edge_type, weight, metadata_json)
                                       VALUES (?, ?, ?, 'ESCALATES_TO', 1.0, ?)""",
                                    (s_slug, prev_mv_id, mv_node_id, json.dumps(escalates_meta)),
                                )

                            last_movement_for_card[target_card_slug] = mv_node_id

                # Character mentions in this movement
                mv_lower = mv["text"].lower()
                for char in chars:
                    pat = rf"\b{re.escape(char['surname'].lower())}\b"
                    if re.search(pat, mv_lower):
                        char_slug = char["person_slug"]
                        char_ord = character_appearance_tracker.get(char_slug, 0) + 1
                        character_appearance_tracker[char_slug] = char_ord

                        role = "first_intro" if char_ord == 1 else "callback"
                        char_node_id = f"char:{s_slug}:{char_slug}"
                        char_meta = {
                            "role": role,
                            "appearance_ordinal": char_ord,
                            "chapter_num": ch_info["chapter_num"],
                            "movement_num": mv["movement_num"],
                        }
                        # Edge 5: FEATURES_CHARACTER (char -> movement)
                        conn.execute(
                            """INSERT INTO okf_edges
                               (series_slug, source_id, target_id, edge_type, weight, metadata_json)
                               VALUES (?, ?, ?, 'FEATURES_CHARACTER', 1.0, ?)""",
                            (s_slug, char_node_id, mv_node_id, json.dumps(char_meta)),
                        )

                # Concept / Jargon translation in this movement
                for j in jargon_items:
                    raw_j_pat = rf"\b{re.escape(j['raw_jargon'].lower())}\b"
                    plain_pat = rf"\b{re.escape(j['plain_english'].lower())}\b"
                    if re.search(raw_j_pat, mv_lower) or re.search(plain_pat, mv_lower):
                        c_id = f"concept:{s_slug}:{j['concept_slug']}"
                        t_meta = {
                            "raw_jargon": j["raw_jargon"],
                            "plain_english": j["plain_english"],
                            "chapter_num": ch_info["chapter_num"],
                        }
                        # Edge 4: TRANSLATES_CONCEPT (concept -> movement)
                        conn.execute(
                            """INSERT INTO okf_edges
                               (series_slug, source_id, target_id, edge_type, weight, metadata_json)
                               VALUES (?, ?, ?, 'TRANSLATES_CONCEPT', 1.0, ?)""",
                            (s_slug, c_id, mv_node_id, json.dumps(t_meta)),
                        )

        # Connect consecutive chapter handoffs within each book
        for b_slug, ch_list in chapters_by_book.items():
            for idx in range(len(ch_list) - 1):
                prev_ch = ch_list[idx]
                curr_ch = ch_list[idx + 1]
                handoff_meta = {
                    "from_closing_anchor": prev_ch["closing_anchor"],
                    "from_takeaway": prev_ch["takeaway_core_rule"],
                    "from_ch_num": prev_ch["chapter_num"],
                    "from_title": prev_ch["title"],
                    "to_prologue_anchor": curr_ch["prologue_anchor"],
                    "to_ch_num": curr_ch["chapter_num"],
                    "to_title": curr_ch["title"],
                }
                # Edge 6: HANDS_OFF_TO (ch_prev -> ch_curr)
                conn.execute(
                    """INSERT INTO okf_edges
                       (series_slug, source_id, target_id, edge_type, weight, metadata_json)
                       VALUES (?, ?, ?, 'HANDS_OFF_TO', 1.0, ?)""",
                    (s_slug, prev_ch["node_id"], curr_ch["node_id"], json.dumps(handoff_meta)),
                )

        # 6. Parse Demand / Keyword Signals from keyword_signals table
        rows = conn.execute(
            """SELECT query, monthly_volume, cpc_high_usd, paa_hook, target_chapter, matched_chapter
               FROM keyword_signals WHERE series_slug = ?""",
            (s_slug,),
        ).fetchall()

        for r in rows:
            q = r["query"]
            cl_slug = re.sub(r"[^a-z0-9]+", "-", q.lower()).strip("-")
            demand_node_id = f"kw:{s_slug}:{cl_slug}"
            d_meta = {
                "canonical_query": q,
                "monthly_volume": r["monthly_volume"],
                "cpc_high_usd": r["cpc_high_usd"],
                "paa_hook": r["paa_hook"] or "",
            }
            conn.execute(
                """INSERT OR REPLACE INTO okf_nodes
                   (node_id, series_slug, book_slug, node_type, label, metadata_json)
                   VALUES (?, ?, ?, 'demand', ?, ?)""",
                (demand_node_id, s_slug, "root", q, json.dumps(d_meta)),
            )

            # Edge 8: ANSWERS_DEMAND (chapter -> demand)
            target_ch = r["target_chapter"] or r["matched_chapter"]
            if target_ch:
                ch_row = conn.execute(
                    """SELECT node_id FROM okf_nodes
                       WHERE series_slug = ? AND node_type = 'chapter' AND (label LIKE ? OR node_id LIKE ?)""",
                    (s_slug, f"%{target_ch}%", f"%{target_ch}%"),
                ).fetchone()
                if ch_row:
                    conn.execute(
                        """INSERT INTO okf_edges
                           (series_slug, source_id, target_id, edge_type, weight, metadata_json)
                           VALUES (?, ?, ?, 'ANSWERS_DEMAND', 1.0, ?)""",
                        (s_slug, ch_row["node_id"], demand_node_id, json.dumps(d_meta)),
                    )

    conn.commit()


# ---------------------------------------------------------------------------
# Context Pack Generator (`compile_chapter_context_pack`)
# ---------------------------------------------------------------------------

def compile_chapter_context_pack(
    series_slug: str,
    chapter_slug: str,
    book_slug: Optional[str] = None,
    repo_root: Optional[Path] = None,
    conn: Optional[sqlite3.Connection] = None,
) -> ChapterContextPack:
    """Traverse 2-hop ego-graph around target chapter to emit Chapter Context Pack."""
    root = repo_root or Path(__file__).resolve().parent.parent
    should_close = False
    if conn is None:
        conn = get_db()
        should_close = True

    try:
        # Check if okf_nodes has data for series; if not, build graph
        count = conn.execute("SELECT count(*) FROM okf_nodes WHERE series_slug = ?", (series_slug,)).fetchone()[0]
        if count == 0:
            build_series_knowledge_graph(conn, root, series_slug)

        # 1. Find Target Chapter Node
        exact_id = f"ch:{series_slug}:{book_slug or 'root'}:{chapter_slug}"
        query = """SELECT node_id, series_slug, book_slug, label, metadata_json FROM okf_nodes
                   WHERE series_slug = ? AND node_type = 'chapter' AND (node_id = ? OR node_id LIKE ?)"""
        ch_node = conn.execute(query, (series_slug, exact_id, f"%:{chapter_slug}")).fetchone()
        if not ch_node and book_slug:
            ch_node = conn.execute(
                """SELECT node_id, series_slug, book_slug, label, metadata_json FROM okf_nodes
                   WHERE series_slug = ? AND book_slug = ? AND node_type = 'chapter' AND node_id LIKE ?""",
                (series_slug, book_slug, f"%:{chapter_slug}%"),
            ).fetchone()
        if not ch_node:
            # Fallback search by chapter_slug substring
            ch_node = conn.execute(
                """SELECT node_id, series_slug, book_slug, label, metadata_json FROM okf_nodes
                   WHERE series_slug = ? AND node_type = 'chapter' AND node_id LIKE ?""",
                (series_slug, f"%{chapter_slug}%"),
            ).fetchone()

        if not ch_node:
            raise ValueError(f"Chapter '{chapter_slug}' not found in series '{series_slug}'")

        ch_id = ch_node["node_id"]
        actual_book_slug = ch_node["book_slug"] or book_slug or "root"
        ch_meta = json.loads(ch_node["metadata_json"])

        pack = ChapterContextPack(
            series_slug=series_slug,
            book_slug=actual_book_slug,
            chapter_slug=ch_meta.get("chapter_slug", chapter_slug),
            chapter_num=ch_meta.get("chapter_num", 1),
            chapter_title=ch_meta.get("title", ch_node["label"]),
            chapter_subtitle=ch_meta.get("subtitle", ""),
        )

        # 2. Adjacent Handoff Envelope (Incoming from Ch K-1, Outgoing to Ch K+1)
        inc_edge = conn.execute(
            """SELECT source_id, metadata_json FROM okf_edges
               WHERE series_slug = ? AND target_id = ? AND edge_type = 'HANDS_OFF_TO'""",
            (series_slug, ch_id),
        ).fetchone()
        if inc_edge:
            meta = json.loads(inc_edge["metadata_json"])
            pack.incoming_handoff = {
                "from_ch_node": inc_edge["source_id"],
                "from_ch_num": meta.get("from_ch_num"),
                "from_title": meta.get("from_title"),
                "closing_anchor": meta.get("from_closing_anchor", ""),
                "takeaway_core_rule": meta.get("from_takeaway", ""),
            }

        out_edge = conn.execute(
            """SELECT target_id, metadata_json FROM okf_edges
               WHERE series_slug = ? AND source_id = ? AND edge_type = 'HANDS_OFF_TO'""",
            (series_slug, ch_id),
        ).fetchone()
        if out_edge:
            meta = json.loads(out_edge["metadata_json"])
            pack.outgoing_handoff = {
                "to_ch_node": out_edge["target_id"],
                "to_ch_num": meta.get("to_ch_num"),
                "to_title": meta.get("to_title"),
                "prologue_anchor": meta.get("to_prologue_anchor", ""),
            }

        # 3. Progressive Lens Escalation Ledger & Epistemic Contract
        # Find all movements belonging to this chapter
        mv_rows = conn.execute(
            """SELECT node_id FROM okf_nodes
               WHERE series_slug = ? AND node_type = 'movement' AND node_id LIKE ?""",
            (series_slug, f"mv:{ch_id}:%"),
        ).fetchall()
        mv_ids = [r["node_id"] for r in mv_rows]

        linked_card_citations: list[dict[str, Any]] = []
        if mv_ids:
            placeholders = ", ".join("?" for _ in mv_ids)
            c_edges = conn.execute(
                f"""SELECT source_id, target_id, metadata_json FROM okf_edges
                    WHERE series_slug = ? AND target_id IN ({placeholders}) AND edge_type = 'CITED_IN_MOVEMENT'""",
                (series_slug, *mv_ids),
            ).fetchall()
            for ce in c_edges:
                cm = json.loads(ce["metadata_json"])
                linked_card_citations.append({
                    "card_node_id": ce["source_id"],
                    "movement_node_id": ce["target_id"],
                    **cm,
                })

        # Also collect from chapter metadata linked_cards if any citations weren't captured
        seen_card_ids: set[str] = set()
        for cit in linked_card_citations:
            cid = cit["card_node_id"]
            if cid in seen_card_ids:
                continue
            seen_card_ids.add(cid)

            card_row = conn.execute(
                "SELECT metadata_json FROM okf_nodes WHERE node_id = ?",
                (cid,),
            ).fetchone()
            if not card_row:
                continue
            c_data = json.loads(card_row["metadata_json"])

            ord_val = cit.get("appearance_ordinal", 1)
            prior_loc = ""
            if ord_val > 1:
                # Find earlier appearance in series
                prior_edge = conn.execute(
                    """SELECT metadata_json FROM okf_edges
                       WHERE series_slug = ? AND source_id = ? AND edge_type = 'CITED_IN_MOVEMENT'
                       ORDER BY edge_id ASC LIMIT 1""",
                    (series_slug, cid),
                ).fetchone()
                if prior_edge:
                    pm = json.loads(prior_edge["metadata_json"])
                    prior_loc = f"Ch.{pm.get('chapter_num', 1)} ({pm.get('chapter_slug')}), Mv.{pm.get('movement_num', 'I')}"

            # Check bounds edge
            bounds_row = conn.execute(
                """SELECT target_id FROM okf_edges
                   WHERE series_slug = ? AND source_id = ? AND edge_type = 'CONTRADICTS_OR_BOUNDS'""",
                (series_slug, cid),
            ).fetchone()
            bounds_edge = bounds_row["target_id"].split(":")[-1] if bounds_row else ""

            pack.escalation_ledger.append({
                "card_slug": c_data.get("card_slug"),
                "title": c_data.get("title"),
                "primary_lens": c_data.get("primary_lens"),
                "certainty_grade": c_data.get("certainty_grade"),
                "appearance_ordinal": ord_val,
                "prior_loc": prior_loc,
                "escalation_plan": c_data.get("escalation_plan", {}),
                "allowed_verbs": c_data.get("allowed_verbs", []),
            })

            pack.epistemic_contract.append({
                "card_slug": c_data.get("card_slug"),
                "certainty_grade": c_data.get("certainty_grade"),
                "attenuation_class": c_data.get("attenuation_class"),
                "allowed_verbs": c_data.get("allowed_verbs", []),
                "forbidden_verbs": c_data.get("forbidden_verbs", []),
                "bounds_edge": bounds_edge,
            })

        # Fallback to chapter's explicit linked cards if empty
        if not pack.escalation_ledger and ch_meta.get("linked_cards"):
            for lc in ch_meta["linked_cards"]:
                card_row = conn.execute(
                    "SELECT metadata_json FROM okf_nodes WHERE series_slug = ? AND node_id LIKE ?",
                    (series_slug, f"%:{lc}"),
                ).fetchone()
                if card_row:
                    c_data = json.loads(card_row["metadata_json"])
                    pack.escalation_ledger.append({
                        "card_slug": c_data.get("card_slug"),
                        "title": c_data.get("title"),
                        "primary_lens": c_data.get("primary_lens"),
                        "certainty_grade": c_data.get("certainty_grade"),
                        "appearance_ordinal": 1,
                        "prior_loc": "",
                        "escalation_plan": c_data.get("escalation_plan", {}),
                        "allowed_verbs": c_data.get("allowed_verbs", []),
                    })
                    pack.epistemic_contract.append({
                        "card_slug": c_data.get("card_slug"),
                        "certainty_grade": c_data.get("certainty_grade"),
                        "attenuation_class": c_data.get("attenuation_class"),
                        "allowed_verbs": c_data.get("allowed_verbs", []),
                        "forbidden_verbs": c_data.get("forbidden_verbs", []),
                        "bounds_edge": "",
                    })

        # 4. Split-Register Metaphors
        concept_rows = conn.execute(
            """SELECT DISTINCT source_id FROM okf_edges
               WHERE series_slug = ? AND target_id IN ({}) AND edge_type = 'TRANSLATES_CONCEPT'""".format(
                ", ".join("?" for _ in mv_ids) if mv_ids else "NULL"
            ),
            (series_slug, *mv_ids) if mv_ids else (series_slug,),
        ).fetchall()
        for cr in concept_rows:
            cnode = conn.execute("SELECT metadata_json FROM okf_nodes WHERE node_id = ?", (cr[0],)).fetchone()
            if cnode:
                cm = json.loads(cnode["metadata_json"])
                pack.metaphor_ledger.append({
                    "concept_slug": cm.get("concept_slug"),
                    "raw_jargon": cm.get("raw_jargon"),
                    "body_prose": cm.get("plain_english"),
                    "spoken_tts": cm.get("spoken_tts"),
                })

        # 5. Character Continuity
        char_rows = conn.execute(
            """SELECT DISTINCT source_id, metadata_json FROM okf_edges
               WHERE series_slug = ? AND target_id IN ({}) AND edge_type = 'FEATURES_CHARACTER'""".format(
                ", ".join("?" for _ in mv_ids) if mv_ids else "NULL"
            ),
            (series_slug, *mv_ids) if mv_ids else (series_slug,),
        ).fetchall()
        for chr_row in char_rows:
            char_node_id = chr_row["source_id"]
            char_node = conn.execute("SELECT label, metadata_json FROM okf_nodes WHERE node_id = ?", (char_node_id,)).fetchone()
            if not char_node:
                continue
            char_meta = json.loads(char_node["metadata_json"])
            edge_meta = json.loads(chr_row["metadata_json"])
            role = edge_meta.get("role", "first_intro")
            guidance = (
                "First introduction in series. Establish biographical framing and historical motivation."
                if role == "first_intro"
                else "Callback appearance. Do NOT repeat biographical appositives (degrees, birth/death dates)."
            )
            pack.character_state.append({
                "full_name": char_node["label"],
                "role": role,
                "first_intro_ch": f"Ch.{edge_meta.get('chapter_num')}" if role == "callback" else "Current Chapter",
                "guidance": guidance,
            })

        # 6. Demand Targets
        demand_rows = conn.execute(
            """SELECT target_id, metadata_json FROM okf_edges
               WHERE series_slug = ? AND source_id = ? AND edge_type = 'ANSWERS_DEMAND'""",
            (series_slug, ch_id),
        ).fetchall()
        for dr in demand_rows:
            dm = json.loads(dr["metadata_json"])
            pack.demand_targets.append({
                "query": dm.get("canonical_query"),
                "monthly_volume": dm.get("monthly_volume", 0),
                "cpc_high_usd": dm.get("cpc_high_usd", 0.0),
                "paa_hook": dm.get("paa_hook", ""),
            })

        return pack

    finally:
        if should_close:
            conn.close()


