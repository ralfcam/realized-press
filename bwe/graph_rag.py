def parse_characters(series_dir: Path) -> list[dict[str, Any]]:
    char_file = series_dir / "characters.md"
    if not char_file.is_file():
        # Fallback to parent
        char_file = series_dir.parent / "characters.md"
    if not char_file.is_file():
        return []

    text = char_file.read_text(encoding="utf-8", errors="replace")
    chars: list[dict[str, Any]] = []

    for block in re.split(r"\n###\s+", text):
        if not block.strip() or block.startswith("#"):
            continue
        lines = block.splitlines()
        header = lines[0].strip()
        # Clean header (e.g. "Frank Rosenblatt (1928–1971)")
        clean_name = re.sub(r"\s*\([^)]*\)", "", header).strip()
        names = [p.strip() for p in re.split(r"&|,", clean_name) if p.strip()]

        summary = " ".join(line.strip() for line in lines[1:] if line.strip())
        role = "Historical researcher"
        if "psychologist" in summary.lower():
            role = "Psychologist / Theorist"
        elif "philosophy" in summary.lower() or "letters" in summary.lower():
            role = "Philosopher"
        elif "thesis" in summary.lower() or "lstm" in summary.lower():
            role = "Computer Scientist / Deep Learning Pioneer"

        for n in names:
            slug = re.sub(r"[^a-z0-9]+", "-", n.lower()).strip("-")
            surname = n.split()[-1]
            chars.append({
                "person_slug": slug,
                "full_name": n,
                "surname": surname,
                "historical_role": role,
                "summary": summary[:200],
            })

    return chars


def parse_jargon(repo_root: Path, series_dir: Path) -> list[dict[str, Any]]:
    candidates = [
        series_dir / "style" / "jargon-to-notes.yml",
        series_dir.parent / "style" / "jargon-to-notes.yml",
        repo_root / "style" / "jargon-to-notes.yml",
    ]
    items: list[dict[str, Any]] = []
    for p in candidates:
        if p.is_file():
            try:
                data = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
                relocate = data.get("relocate_to_notes") or {}
                for k, v in relocate.items():
                    slug = re.sub(r"[^a-z0-9]+", "-", str(k).lower()).strip("-")
                    items.append({
                        "concept_slug": slug,
                        "raw_jargon": str(k),
                        "plain_english": str(v),
                        "spoken_tts": str(v),
                    })
            except Exception:
                pass
            if items:
                break
    return items


def parse_sources_bib(bib_path: Path) -> dict[str, dict[str, Any]]:
    if not bib_path.is_file():
        return {}
    text = bib_path.read_text(encoding="utf-8", errors="replace")
    entries: dict[str, dict[str, Any]] = {}
    pattern = re.compile(r"@(\w+)\s*\{\s*([^,\s]+),([^@]*)\}", re.DOTALL)
    for m in pattern.finditer(text):
        entry_type = m.group(1).lower()
        bib_key = m.group(2).strip()
        body = m.group(3)
        title_m = re.search(r"title\s*=\s*\{([^}]+)\}", body, re.IGNORECASE)
        doi_m = re.search(r"doi\s*=\s*\{([^}]+)\}", body, re.IGNORECASE)
        year_m = re.search(r"year\s*=\s*\{?(\d{4})\}?", body, re.IGNORECASE)
        author_m = re.search(r"author\s*=\s*\{([^}]+)\}", body, re.IGNORECASE)
        entries[bib_key] = {
            "bib_key": bib_key,
            "entry_type": entry_type,
            "title": title_m.group(1).strip() if title_m else bib_key,
            "doi": doi_m.group(1).strip() if doi_m else "",
            "year": int(year_m.group(1)) if year_m else 0,
            "authors": author_m.group(1).strip() if author_m else "",
        }
    return entries


# ---------------------------------------------------------------------------
