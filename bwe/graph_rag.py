# Regex patterns for chapter parsing
INLINE_FN_RE = re.compile(r"(?<!^)\[\^([^\]]+)\](?!:)")
DEF_FN_RE = re.compile(r"^\[\^([^\]]+)\]:\s*(.+)$", re.MULTILINE)
HEADING_RE = re.compile(r"^(##+)\s+(.+)$", re.MULTILINE)
MOVEMENT_HEADING_RE = re.compile(r"^##\s+([IVXLCDM]+|\d+)\.\s+(.+)$", re.MULTILINE)
LINKED_CARD_RE = re.compile(r"[-*]\s*(?:`|\[)?(?:evidence-cards/)?([a-z0-9-]+)(?:\.md)?(?:`|\])?", re.IGNORECASE)
CARD_IN_NOTE_RE = re.compile(r"Evidence Cards?:\s*`?(?:evidence-cards/)?([a-z0-9-]+)(?:\.md)?`?", re.IGNORECASE)

# High-certainty causal claim verbs vs moderate/low verbs
HIGH_CERTAINTY_VERBS = {
    "shows", "show", "showed", "demonstrates", "demonstrate", "demonstrated",
    "establishes", "establish", "established", "proves", "prove", "proved",
    "causes", "cause", "caused", "prevents", "prevent", "prevented",
    "preserves", "preserve", "preserved", "confirms", "confirm", "confirmed",
}
MODERATE_CERTAINTY_VERBS = {
    "suggests", "suggest", "suggested", "indicates", "indicate", "indicated",
    "points", "points toward", "implies", "imply", "implied",
}
LOW_CERTAINTY_VERBS = {
    "is associated with", "are associated with", "correlates with", "correlate with",
    "tracks with", "track with", "co-occurs with", "co-occur with",
}
ALL_EPISTEMIC_VERBS = HIGH_CERTAINTY_VERBS | MODERATE_CERTAINTY_VERBS | LOW_CERTAINTY_VERBS


@dataclass
class OKFNode:
    node_id: str
    series_slug: str
    book_slug: Optional[str]
    node_type: str
    label: str
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class OKFEdge:
    edge_id: Optional[int]
    series_slug: str
    source_id: str
    target_id: str
    edge_type: str
    weight: float = 1.0
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class ChapterContextPack:
    series_slug: str
    book_slug: str
    chapter_slug: str
    chapter_num: int
    chapter_title: str
    chapter_subtitle: str
    incoming_handoff: dict[str, Any] = field(default_factory=dict)
    outgoing_handoff: dict[str, Any] = field(default_factory=dict)
    escalation_ledger: list[dict[str, Any]] = field(default_factory=list)
    epistemic_contract: list[dict[str, Any]] = field(default_factory=list)
    metaphor_ledger: list[dict[str, Any]] = field(default_factory=list)
    character_state: list[dict[str, Any]] = field(default_factory=list)
    demand_targets: list[dict[str, Any]] = field(default_factory=list)
    typed_causal_edges: list[dict[str, Any]] = field(default_factory=list)
    suggested_unlinked_cards: list[dict[str, Any]] = field(default_factory=list)
    quantitative_anchors: list[dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def _build_markdown_lines(self) -> list[str]:
        lines: list[str] = [
            f"# Chapter Context Pack: Ch.{self.chapter_num:02d} — {self.chapter_title}",
            f"> Series: `{self.series_slug}` | Book: `{self.book_slug}` | Chapter: `{self.chapter_slug}`",
            "> Context Budget: ~__TOKEN_BUDGET__ tokens | Generated by BWE Graph RAG Engine (OKF v0.3)",
            "",
            "---",
            "",
            "## 1. Tier 1: Direct 1-Hop Cited Cards & Epistemic Contracts",
            "",
        ]

        if self.escalation_ledger:
            for item in self.escalation_ledger:
                b_ord = item.get("book_ordinal", item.get("appearance_ordinal", 1))
                s_ord = item.get("series_ordinal", b_ord)
                lines.extend([
                    f"### Card: `{item.get('card_slug')}` — *{item.get('title')}*",
                    f"- **Certainty Grade:** `{item.get('certainty_grade')}` | **Primary Lens:** `{item.get('primary_lens')}` | **Book Ordinal:** `{b_ord}` | **Series Ordinal:** `{s_ord}`",
                    f"- **Escalation Instruction:** {item.get('escalation_directive', 'Progressive lens escalation applies.')}",
                ])
                plan = item.get("escalation_plan", {})
                if plan and str(b_ord) in plan:
                    lines.append(f"- **Author Escalation Plan:** {plan[str(b_ord)]}")
                lines.append("")
        else:
            lines.append("*No dedicated OKF evidence cards currently anchored to this chapter.*")
            lines.append("")

        lines.extend([
            "### Epistemic Verb & Claim Boundary Contract",
            "",
        ])

        if self.epistemic_contract:
            lines.extend([
                "| Card Slug | Grade | Attenuation Class | Allowed Claim Verbs | Forbidden Claim Verbs | Bounding / Revision Edge |",
                "| :--- | :--- | :--- | :--- | :--- | :--- |",
            ])
            for ep in self.epistemic_contract:
                allowed_list = ep.get("allowed_verbs", [])
                allowed = ", ".join(f"`{v}`" for v in allowed_list[:3])
                forbidden_list = ep.get("forbidden_verbs", [])
                forbidden = ", ".join(f"`{v}`" for v in forbidden_list[:2])
                bounds = ep.get("bounds_edge") or "None"
                lines.append(
                    f"| `{ep.get('card_slug')}` | **{ep.get('certainty_grade')}** | `{ep.get('attenuation_class')}` | {allowed} | {forbidden} | {bounds} |"
                )
            lines.append("")
        else:
            lines.append("*Standard Grade-to-Verb Protocol applies: High -> shows; Moderate -> suggests; Low -> is associated with.*")
            lines.append("")

        if self.quantitative_anchors:
            lines.extend([
                "### Quantitative Anchors & Benchmark Constants",
                "",
                "| Card Slug | Verified Quantitative Figures / Empirical Anchors |",
                "| :--- | :--- |",
            ])
            for qa in self.quantitative_anchors:
                clean_anchors = [
                    (a[:100] + "..." if len(a) > 100 else a)
                    for a in qa.get("anchors", [])[:2]
                ]
                anchors_str = "; ".join(f"`{a}`" for a in clean_anchors)
                lines.append(f"| `{qa.get('card_slug')}` | {anchors_str} |")
            lines.append("")

        lines.extend([
            "---",
            "",
            "## 2. Tier 2: 2-Hop Typed Causal Argument Map & Narrative Handoff Envelope",
            "",
        ])

        if self.typed_causal_edges:
            lines.extend([
                "### Typed Causal Argument Map (2-Hop Card Neighbors)",
                "",
                "| Source Card | Relationship | Related Card | Target Lens & Grade |",
                "| :--- | :--- | :--- | :--- |",
            ])
            for te in self.typed_causal_edges[:6]:
                lines.append(
                    f"| `{te.get('source_card')}` | **{te.get('relationship')}** | `{te.get('target_card')}` (*{te.get('target_title', '')[:25]}*) | `{te.get('target_lens', '')}` [{te.get('target_grade', '')}] |"
                )
            lines.append("")

        lines.extend([
            "### Adjacent Handoff Envelope (Sequential 1-Hop Chapter Neighbors)",
            "",
        ])

        # Incoming handoff
        inc = self.incoming_handoff
        if inc:
            c_anchor = inc.get("closing_anchor", "N/A")
            if len(c_anchor) > 180:
                c_anchor = c_anchor[:177] + "..."
            lines.extend([
                f"#### Incoming Bridge (From Ch.{inc.get('from_ch_num', 'K-1')} Close: *{inc.get('from_title', 'Previous Chapter')}*)",
                "- **Closing Narrative Anchor:**",
                f"  > {c_anchor}",
                f"- **Takeaway Core Rule:** {inc.get('takeaway_core_rule', 'N/A')}",
                f"- **Handoff Directive:** Pick up this conceptual thread without repeating the conclusion. Do not re-summarize what Ch.{inc.get('from_ch_num', 'K-1')} already proved.",
                "",
            ])
        else:
            lines.extend([
                "#### Incoming Bridge: Volume / Series Opening",
                "- **Opening Directive:** This is Chapter 01. Establish the foundational epistemic contract and sensory hook.",
                "",
            ])

        # Outgoing handoff
        out = self.outgoing_handoff
        if out:
            p_anchor = out.get("prologue_anchor", "N/A")
            if len(p_anchor) > 180:
                p_anchor = p_anchor[:177] + "..."
            lines.extend([
                f"#### Outgoing Bridge (To Ch.{out.get('to_ch_num', 'K+1')} Open: *{out.get('to_title', 'Next Chapter')}*)",
                "- **Opening Scene / Question:**",
                f"  > {p_anchor}",
                f"- **Handoff Boundary:** Do not prematurely resolve Ch.{out.get('to_ch_num', 'K+1')}'s central question.",
                "",
            ])
        else:
            lines.extend([
                "#### Outgoing Bridge: Volume / Series Finale",
                "- **Closing Directive:** This is the concluding chapter. Synthesize the multi-lens arc without introducing ungrounded new paradigms.",
                "",
            ])

        lines.extend([
            "---",
            "",
            "## 3. Tier 3: Latent Evidence Discovery (Suggested Unlinked Cards)",
            "",
        ])

        if self.suggested_unlinked_cards:
            lines.extend([
                "| Card Slug | Title | Grade & Lens | BM25 Overlap | Recommendation |",
                "| :--- | :--- | :--- | :--- | :--- |",
            ])
            for su in self.suggested_unlinked_cards:
                lines.append(
                    f"| `{su.get('card_slug')}` | *{su.get('title')}* | `{su.get('certainty_grade')}` / `{su.get('primary_lens')}` | `{su.get('bm25_score'):.3f}` | Internal series match: check card before external research. |"
                )
            lines.append("")
        else:
            lines.append("*Zero unlinked cards with high BM25 overlap; evidentiary coverage is tightly isolated to Tier 1 cited cards.*")
            lines.append("")

        lines.extend([
            "---",
            "",
            "## 4. Split-Register Metaphor & Voice Continuity Ledger",
            "",
        ])

        if self.metaphor_ledger:
            lines.extend([
                "| Concept / Jargon | Banned Body Term | Canonical Body Metaphor | Spoken Audio (TTS) Form |",
                "| :--- | :--- | :--- | :--- |",
            ])
            for m in self.metaphor_ledger:
                lines.append(
                    f"| `{m.get('concept_slug')}` | `{m.get('raw_jargon')}` | *{m.get('body_prose')}* | *{m.get('spoken_tts')}* |"
                )
            lines.append("")
        else:
            lines.append("*Maintain split-register discipline: clinical/mathematical terms reside strictly in `## Notes`.*")
            lines.append("")

        lines.extend([
            "---",
            "",
            "## 5. Character Continuity State",
            "",
        ])

        if self.character_state:
            lines.extend([
                "| Character | Role in Chapter | Prior Introduction | Continuity Guidance |",
                "| :--- | :--- | :--- | :--- |",
            ])
            for c in self.character_state:
                lines.append(
                    f"| **{c.get('full_name')}** | `{c.get('role')}` | {c.get('first_intro_ch', 'Current Chapter')} | {c.get('guidance')} |"
                )
            lines.append("")
        else:
            lines.append("*No recurring historical figures tracked in this chapter.*")
            lines.append("")

        lines.extend([
            "---",
            "",
            "## 6. Demand & People-Also-Ask (PAA) Weave Targets",
            "",
        ])

        if self.demand_targets:
            lines.extend([
                "| Target Query | Monthly Volume | CPC Ceiling | Natural PAA Hook / Integration Angle |",
                "| :--- | ---: | ---: | :--- |",
            ])
            for d in self.demand_targets[:6]:
                lines.append(
                    f"| `{d.get('query')}` | {d.get('monthly_volume', 0):,} | ${d.get('cpc_high_usd', 0.0):.2f} | *{d.get('paa_hook', 'N/A')}* |"
                )
            lines.append("")
        else:
            lines.append("*General audience inquiry: align prose with Quick-Finder intent.*")
            lines.append("")

        return lines

